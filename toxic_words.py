"""Распознавание грубости и мата для Хамульки.

STRONG — мат и явные оскорбления: если нашлось, это точно наезд, балл ставится всегда.
WEAK   — слова, которые бывают и безобидными (наглый, бред, свали...): их проверяет нейросеть,
         и балл ставится, только если она решит, что это правда наезд.
"""
import re

# Похожие латинские буквы и цифры, которыми маскируют мат (xyй, 6ля, n1zда)
LOOKALIKES = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к", "m": "м", "o": "о", "p": "р",
    "t": "т", "x": "х", "y": "у", "u": "и", "n": "п", "r": "г",
    "0": "о", "3": "з", "4": "ч", "6": "б", "@": "а", "$": "с", "ё": "е",
})

# Безобидные слова, внутри которых прячутся "плохие" кусочки: их убираем перед проверкой
SAFE_WORDS = [
    r"хамульк\w*", r"страху\w*", r"застрах\w*", r"употребл\w*", r"оскорбл\w*", r"истребл\w*",
    r"корабл\w*", r"сабл\w*", r"рубл\w*", r"колебл\w*", r"скребл\w*", r"тупик\w*", r"доступ\w*",
    r"поступ\w*", r"наступ\w*", r"выступ\w*", r"уступ\w*", r"ступен\w*", r"бесплатн\w*",
    r"сукн\w*", r"скотч\w*", r"тварог", r"барабан\w*", r"лохмат\w*", r"дурман\w*",
    r"козерог\w*", r"рыбл\w*", r"гребл\w*", r"психолог\w*", r"бляшк\w*", r"блэк\w*",
    r"оскребл\w*", r"страхов\w*", r"подстрах\w*",
]
# слово целиком, если безобидный кусок стоит в любом месте слова
SAFE_PATTERN = re.compile(r"[а-яёa-z]*(" + "|".join(w.replace("\\w*", "") for w in SAFE_WORDS) + r")[а-яёa-z]*", re.IGNORECASE)

# Мат и явные оскорбления (кусочки, которые ни с чем не спутать)
STRONG = [
    # мат
    r"х[уy\*][йяеёиюj]", r"п[иі\*][зz]д", r"\bе[бп\*][аeоуиы]?[тлнк]", r"\bё[бп]", r"[ыа]еб", r"уеб", r"заеб", r"наеб",
    r"выеб", r"отъеб", r"съеб", r"долб[оа]еб", r"\bбл[яэ\*]", r"\bбл\b", r"\bсук[аиоуеэ]?\b", r"\bсучк", r"\bсучар",
    r"мудак", r"мудил", r"мудозвон", r"г[ао]ндон", r"шлюх", r"шалав", r"пид[оа]р", r"\bпидр", r"\bпедик",
    r"\bхер\b", r"нахер", r"похер", r"\bпоху(й|ю|я)?\b", r"\bпохуист", r"\bнаху", r"прошмандов", r"\bшмар",
    r"\bсоси\b", r"отсоси", r"\bнищеброд", r"\bуебищ", r"\bпидорас", r"\bхуесос", r"\bмразот", r"охренел", r"охуе", r"ахуе", r"\bжоп",
    # явные оскорбления
    r"мраз", r"гнид", r"\bтвар[ьи]", r"ублюд", r"\bпадл", r"выродок", r"уебок", r"ушл[её]п", r"\bчмо",
    r"дебил", r"\bидиот", r"кретин", r"придур", r"\bдаун\b", r"имбецил", r"олигофрен", r"тупорыл",
    r"\bтупиц", r"\bдурак", r"\bдур[аыеоу]\b", r"\bдурой\b", r"\bдурочк", r"\bдурень", r"\bдебилк",
    r"\bкоз[её]л", r"\bкозл[аыу]", r"\bскотин", r"\bсвинь[яи]\b", r"\bурод", r"\bлох\b", r"\bлох[аиу]\b",
    r"\bлошар", r"\bлохушк", r"\bчушпан", r"\bклоун", r"\bовц[аы]\b", r"\bкрыс[аы]\b", r"\bшавк",
    r"\bдерьм", r"\bговн", r"\bуебан", r"\bдолбан",
    r"\bзаткнис", r"\bзаткни\b", r"закрой (рот|пасть|варежку|хлебальник)", r"(рот|пасть) закрой",
    r"иди (нах|в жопу|лесом|к черту)", r"пош[её]л (нах|вон|в жопу)", r"пошла (нах|вон|в жопу)",
    r"\bотвали\b", r"\bотъебись", r"\bвали отсюда", r"\bхамло\b", r"\bхамка\b",
]

# Бывает и безобидным: решает нейросеть
WEAK = [
    r"\bхам", r"нахал", r"\bнагл", r"\bдерз", r"выпендр", r"\bпонт", r"\bбред", r"\bофиг", r"\bафиг",
    r"\bохрин", r"\bахрин", r"\bзавал", r"\bсвал", r"\bпош[её]л\b", r"\bпошла\b", r"\bлузер", r"\bнуб\b",
    r"\bбомж", r"\bбаран", r"\bкурица\b", r"\bистеричк", r"\bзануд", r"\bбесишь", r"\bбесит",
    r"\bненавижу", r"\bотстань", r"\bотвянь", r"\bкатись", r"\bзадолбал", r"\bдостал[аи]?\b",
    r"\bуйди\b", r"\bфу\b", r"\bкринж", r"\bнеадекват", r"\bпсих\b", r"\bпсихичк",
    r"\bтуп(ой|ая|ое|ые|ого|ую)\b", r"\bмудрил", r"\bдно\b",
]

STRONG_PATTERN = re.compile("|".join(STRONG), re.IGNORECASE)
WEAK_PATTERN = re.compile("|".join(WEAK), re.IGNORECASE)


def normalize(text):
    """Приводит текст к виду, в котором маскировка мата не помогает."""
    t = (text or "").lower()
    t = SAFE_PATTERN.sub(" ", t)
    t = t.translate(LOOKALIKES)
    t = re.sub(r"(?<=[а-я])[.\-_](?=[а-я])", "", t)   # х.у.й -> хуй
    t = re.sub(r"([а-я])\1{2,}", r"\1", t)              # сууука -> сука
    t = SAFE_PATTERN.sub(" ", t)
    return t


def check_toxicity(text):
    """Возвращает 'strong', 'weak' или None."""
    t = normalize(text)
    if STRONG_PATTERN.search(t):
        return "strong"
    if WEAK_PATTERN.search(t):
        return "weak"
    return None
