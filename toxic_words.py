STRONG_PATTERN = re.compile("|".join(STRONG), re.IGNORECASE)
WEAK_PATTERN = re.compile("|".join(WEAK), re.IGNORECASE)
EN_PATTERN = re.compile("|".join(EN_STRONG), re.IGNORECASE)
MAYBE_PATTERN = re.compile("|".join(MAYBE), re.IGNORECASE)
def is_shouting(text):
    """КРИК КАПСОМ: много русских букв, и почти все большие."""
    letters = [ch for ch in (text or "") if ch.isalpha() and ("а" <= ch.lower() <= "я" or ch.lower() == "ё")]
    upper = sum(ch.isupper() for ch in letters)
    return len(letters) >= 8 and upper / len(letters) > 0.8


def normalize(text):
    """Приводит текст к виду, в котором маскировка мата не помогает."""
    t = (text or "").lower()
    t = SAFE_PATTERN.sub(" ", t)
    t = t.translate(LOOKALIKES)
    t = re.sub(r"(?<=[а-я])[.\-_](?=[а-я])", "", t)   # х.у.й -> хуй
    t = re.sub(r"([а-я])\1{2,}", r"\1", t)              # сууука -> сука
    t = SAFE_PATTERN.sub(" ", t)
    return t


def check_toxicity(text):
    """Возвращает 'strong' (точно наезд), 'weak' (грубое слово), 'maybe' (похоже на подкол) или None."""
    t = normalize(text)
    if STRONG_PATTERN.search(t) or EN_PATTERN.search(text or ""):
        return "strong"
    if WEAK_PATTERN.search(t):
        return "weak"
    if MAYBE_PATTERN.search(t) or is_shouting(text) or "!!!" in (text or ""):
        return "maybe"
    return None
